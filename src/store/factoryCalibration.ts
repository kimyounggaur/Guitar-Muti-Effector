export function factoryTrimDb(category: string, index: number): number {
  const measurement = factoryMeasurement[category]?.[index];
  if (!measurement) return 0;
  const [rmsDb, peakDb] = measurement;
  // Target -45 dBFS RMS for this test, while keeping its peak under -8 dBFS.
  // Never boost a quiet patch and never attenuate by more than 36 dB.
  return Math.round(Math.max(-36, Math.min(0, -45 - rmsDb, -8 - peakDb)) * 100) / 100;
}
