export type MessageKey = keyof typeof ko;

/** Looks up a message and replaces {name} placeholders. */
export const t = (key: MessageKey, vars?: Record<string, string | number>): string => {
  const text: string = ko[key];
  return vars ? text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match)) : text;
};

/** Message lookup for keys built at run time (e.g. 'param.' + type + '.' + name); falls back to the given text. */
/** On-screen name of a preset category; unknown categories (e.g. imported ones) are shown as they are. */
export const formatCategory = (category: string): string => tDynamic(`preset.category.${category}`, category);

export const tDynamic = (key: string, fallback: string): string => (key in ko ? ko[key as MessageKey] : fallback);
